// 按关键词检索匹配的离线地理预设，优先展示前缀命中的常用地点。
export function searchGeoPresets(query: string, limit = 8): GeoPreset[] {
  const term = query.trim().toLowerCase();
  if (!term) return GEO_PRESETS.slice(0, limit);
  const exact: GeoPreset[] = [];
  const partial: GeoPreset[] = [];
  for (const item of GEO_PRESETS) {
    if (item.label.toLowerCase().startsWith(term) || item.city.toLowerCase().startsWith(term)) exact.push(item);
    else if (item.search.includes(term)) partial.push(item);
    if (exact.length + partial.length >= limit * 3) break;
  }
  return [...exact, ...partial].slice(0, limit);
}

// 将历史手填的中文国家名或省份简称归一化为离线 GeoJSON 区域名称，提升地图高亮命中率。
export function normalizeMapRegionName(mode: "world" | "china" | "city", raw: string | null): string | null {
  const value = raw?.trim();
  if (!value) return null;
  if (mode === "world") return COUNTRY_ALIASES[value] ?? value;
  if (mode === "china") return PROVINCE_ALIASES[value] ?? value;
  return value;
}
